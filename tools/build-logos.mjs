// Bundles the logos named in ui/brands.js into ui/logos.js so the island never fetches icons from the web.
// Run after adding a brand:  node tools/build-logos.mjs
import fs from 'node:fs';
import { createRequire } from 'node:module';
import * as si from 'simple-icons';
import { BRANDS } from '../ui/brands.js';

const require = createRequire(import.meta.url);
const L = require('@iconify-json/logos/icons.json'); // SVG Logos by Gil Barbara, CC0
const url = svg => 'data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64');

function svgLogos(id) {
  const alias = L.aliases?.[id];
  const icon = L.icons[alias?.parent || id];
  if (!icon) return null;
  const w = icon.width ?? L.width ?? 256, h = icon.height ?? L.height ?? 256;
  // full-color logo on a light tile (some logos are black and would vanish on the dark glass)
  return { src: url(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${icon.body}</svg>`), bg: '#FFFFFF' };
}

function simpleIcons(id) {
  const icon = si['si' + id[0].toUpperCase() + id.slice(1)];
  if (!icon) return null;
  // single-color glyph in white on its brand color, like the real app tile
  return { src: url(icon.svg.replace('<svg ', '<svg fill="#FFFFFF" ')), bg: '#' + icon.hex };
}

const out = {}, missing = [];
for (const b of BRANDS) {
  if (!b.logo) continue;
  const [set, id] = b.logo.split(':');
  const logo = set === 'L' ? svgLogos(id) : simpleIcons(id);
  if (logo) out[b.name] = logo; else missing.push(`${b.name} (${b.logo})`);
}
fs.writeFileSync(new URL('../ui/logos.js', import.meta.url),
  '// Generated by tools/build-logos.mjs from SVG Logos and Simple Icons (both CC0). Do not edit.\n' +
  `export const LOGOS = ${JSON.stringify(out)};\n`);
console.log(`bundled ${Object.keys(out).length} logos` + (missing.length ? `; missing: ${missing.join(', ')}` : ''));
if (missing.length) process.exitCode = 1;
